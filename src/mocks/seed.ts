export function toChatJob(job: CatalogJob): Job {
	return {
		job_title: job.job_title,
		company_name: job.company_name,
		match_percent: job.match_percent,
		requirements: job.requirements,
		job_url: job.job_url,
		source_site: job.source_site ?? "",
		company_reviews: job.company_reviews,
		paycheck: job.paycheck,
	};
}

export function pickJobs(ids: number[]): Job[] {
	return ids.map((id) => {
		const job = catalog.find((item) => item.job_id === id);
		if (!job) throw new Error(`Missing mock job ${id}`);
		return toChatJob(job);
	});
}

