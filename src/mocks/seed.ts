function listing(
	jobId: number,
	title: string,
	company: string,
	location: string | null,
	paycheck: string | null,
	source: string | null,
	match: number,
	embedded: boolean,
	requirements: [string, string, string],
	rawText: string,
	reviews: { rating: number; count: number } | null,
	slug: string,
): CatalogJob {
	const host =
		source === "جاب‌ویژن"
			? "https://jobvision.ir/jobs"
			: "https://jobinja.ir/companies";

	return {
		job_id: jobId,
		job_title: title,
		company_name: company,
		location,
		paycheck,
		source_site: source,
		match_percent: match,
		has_embedding: embedded,
		requirements,
		raw_text: rawText,
		company_reviews: reviews,
		job_url: `${host}/${slug}-${jobId}`,
	};
}

